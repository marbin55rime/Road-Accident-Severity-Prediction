df[num_cols] = df[num_cols].fillna(df[num_cols].median())


cat_cols = df.select_dtypes(include=['object']).columns
for col in cat_cols:
    df[col] = df[col].fillna(df[col].mode()[0])

"""Encoding Categorical Data"""

le = LabelEncoder()

for col in cat_cols:
    df[col] = le.fit_transform(df[col])

"""Encoding the Target"""

df['Weather_y'] = LabelEncoder().fit_transform(df['Weather_y'])

"""Split Data"""

X = df.drop('Weather_y', axis=1)
y = df['Weather_y']

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42)

"""Feature Scaling"""

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

"""Train Models"""

models = {
    "Naive Bayes": GaussianNB(),
    "Logistic Regression": LogisticRegression(max_iter=1000),
    "Neural Network": MLPClassifier(hidden_layer_sizes=(100,), max_iter=1000, random_state=42),
    "Random Forest": RandomForestClassifier(n_estimators=100, random_state=42)}

"""Evaluation Function"""

def evaluate_model(name, model, X_test, y_test):
    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)

    accuracy = accuracy_score(y_test, y_pred)
    precision = precision_score(y_test, y_pred, average='weighted')
    recall = recall_score(y_test, y_pred, average='weighted')
    f1 = f1_score(y_test, y_pred, average='weighted')
    auc = roc_auc_score(y_test, y_proba, multi_class='ovr')

    print(f"\n{name} Results")
    print("="*40)
    print(f"Accuracy: {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall: {recall:.4f}")
    print(f"F1 Score: {f1:.4f}")
    print(f"AUC: {auc:.4f}")

    print("\nClassification Report:\n", classification_report(y_test, y_pred))

    return accuracy, precision, recall, f1, auc, y_pred, y_proba

"""Evaluate All Models"""

results = []
predictions = {}

for name, model in models.items():
    model.fit(X_train_scaled, y_train)
    acc, prec, rec, f1, auc, y_pred, y_proba = evaluate_model(name, model, X_test_scaled, y_test)

    results.append([name, acc, prec, rec, f1, auc])
    predictions[name] = (y_pred, y_proba)

